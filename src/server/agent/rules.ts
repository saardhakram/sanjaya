import type { Confidence, Incident, IncidentAssessment, TriageReport } from '../../shared/types.js';
import type { EngineResult } from '../engine/analyze.js';

/**
 * Deterministic triage report used when the AI is disabled, unconfigured or
 * fails. It guarantees every request returns a complete, useful result.
 */

const OBJECTIVES: readonly [string, string][] = [
  ['Persistence', 'Keep long-term access to the system (backdoor account).'],
  ['Privilege Escalation', 'Gain full administrative (root) control.'],
  ['Initial Access', 'Get a foothold on the system or application.'],
  ['Credential Access', 'Obtain valid account credentials.'],
  ['Defense Evasion', 'Manipulate defenders or automated analysis tools.'],
  ['Discovery', 'Map exposed services for a later attack.'],
  ['Reconnaissance', 'Find weaknesses to exploit.'],
];

function objectiveFor(incident: Incident): string {
  for (const [tactic, text] of OBJECTIVES) if (incident.tactics.includes(tactic)) return text;
  return 'Unclear; review the evidence.';
}

function confidenceFor(score: number): Confidence {
  if (score >= 85) return 'high';
  if (score >= 60) return 'medium';
  return 'low';
}

export function rulesTriage(state: EngineResult): TriageReport {
  const { incidents, stats } = state;
  const assessments: IncidentAssessment[] = incidents.map((inc, i) => {
    const details = state.findings
      .filter((f) => inc.findingIds.includes(f.id))
      .map((f) => f.details)
      .slice(0, 3)
      .join(' ');
    return {
      incidentId: inc.id,
      priority: i + 1,
      assessment: details,
      attackerObjective: objectiveFor(inc),
      confidence: confidenceFor(inc.score),
      likelyTruePositive: inc.score >= 50,
    };
  });

  const top = incidents[0];
  const executiveSummary =
    incidents.length === 0
      ? `No suspicious activity was detected in ${stats.linesTotal} log lines. No action is needed.`
      : `${incidents.length} incident(s) found in ${stats.linesTotal} log lines (${stats.critical} critical, ${stats.high} high). ` +
        `Handle first: ${top!.id}, "${top!.title}".`;

  return {
    executiveSummary,
    assessments,
    analystNotes:
      'Generated by rule-based triage. Enable the Gemini analyst for a narrative investigation.',
  };
}
