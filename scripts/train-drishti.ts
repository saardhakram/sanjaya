/**
 * Trains Drishti, Sanjaya's anomaly-detection model, and writes it to
 * src/server/ml/model.generated.ts.
 *
 *   npm run train:ml                       # synthetic benign baseline only
 *   npm run train:ml -- normal1.log ...    # add your own known-good logs
 *
 * Training is fully deterministic (fixed seeds), so the committed model can be
 * reproduced exactly; a unit test checks this.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseLogs } from '../src/server/engine/parsers.js';
import { trainDrishti } from '../src/server/ml/train.js';
import { profilesFrom } from '../src/server/ml/features.js';

const extra = process.argv
  .slice(2)
  .flatMap((file) =>
    profilesFrom(
      parseLogs(readFileSync(file, 'utf8'), { referenceYear: new Date().getUTCFullYear() }).events,
    ),
  );

const { model, report } = trainDrishti(extra);

const out = fileURLToPath(new URL('../src/server/ml/model.generated.ts', import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/train-drishti.ts. Do not edit by hand; run \`npm run train:ml\`.\n` +
    `import type { DrishtiModel } from './model.js';\n\n` +
    `export const DRISHTI_MODEL: DrishtiModel = ${JSON.stringify(model)};\n`,
);

console.log(
  `Drishti ${model.version}: ${model.trainingProfiles} benign profiles (${extra.length} from your logs)`,
);
for (const g of report) {
  console.log(
    `  ${g.group.padEnd(8)} rows=${g.rows} evidence p50=${g.evidenceP50.toFixed(2)} p99=${g.evidenceP99.toFixed(2)} max=${g.evidenceMax.toFixed(2)} threshold=${g.threshold} FPR=${(g.falsePositiveRate * 100).toFixed(2)}%`,
  );
}
console.log(`Wrote ${out}`);
